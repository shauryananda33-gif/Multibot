-- MULTIBOT2 durable state schema for Supabase Postgres.
-- Runtime state is stored in a non-exposed schema, not the public Data API.

CREATE SCHEMA IF NOT EXISTS multibot;
REVOKE ALL ON SCHEMA multibot FROM PUBLIC;
REVOKE ALL ON SCHEMA multibot FROM anon, authenticated;
GRANT USAGE ON SCHEMA multibot TO postgres;

CREATE TABLE IF NOT EXISTS multibot.accounts (
    name TEXT PRIMARY KEY,
    starting_balance DOUBLE PRECISION NOT NULL,
    balance DOUBLE PRECISION NOT NULL,
    trades_today INTEGER NOT NULL DEFAULT 0,
    planned_risk_used DOUBLE PRECISION NOT NULL DEFAULT 0,
    reset_date TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS multibot.trades (
    id TEXT PRIMARY KEY, status TEXT NOT NULL, payload TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS multibot.signals (
    signal_key TEXT PRIMARY KEY, send_count INTEGER NOT NULL DEFAULT 0,
    first_sent_at TEXT, last_sent_at TEXT, reminder_due_at TEXT,
    reminder_sent INTEGER NOT NULL DEFAULT 0, message_text TEXT, metadata TEXT
);
CREATE TABLE IF NOT EXISTS multibot.signal_events (
    signal_id TEXT PRIMARY KEY, signal_key TEXT NOT NULL UNIQUE, strategy TEXT NOT NULL,
    version TEXT, symbol TEXT NOT NULL, direction TEXT NOT NULL, timestamp TEXT NOT NULL,
    timeframe TEXT, reason TEXT, pipeline_status TEXT NOT NULL, metadata TEXT,
    created_at TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS multibot.deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, signal_id TEXT NOT NULL,
    channel TEXT NOT NULL, status TEXT NOT NULL, attempted_at TEXT NOT NULL,
    error TEXT, message_type TEXT, metadata TEXT
);
CREATE TABLE IF NOT EXISTS multibot.scan_runs (
    id TEXT PRIMARY KEY, strategy_id TEXT NOT NULL, started_at TEXT NOT NULL,
    finished_at TEXT, status TEXT NOT NULL, payload TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS multibot.scan_error_alerts (
    strategy_id TEXT PRIMARY KEY, fingerprint TEXT NOT NULL, first_sent_at TEXT NOT NULL,
    last_sent_at TEXT NOT NULL, suppressed INTEGER NOT NULL DEFAULT 0, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS multibot.market_data_cache (
    cache_key TEXT PRIMARY KEY, symbol TEXT NOT NULL, period TEXT NOT NULL, interval TEXT NOT NULL,
    validate_hourly INTEGER NOT NULL, payload TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS multibot.forex_calendar_week_cache (
    feed_key TEXT NOT NULL, week_start TEXT NOT NULL, fetched_at TEXT NOT NULL,
    events TEXT NOT NULL, PRIMARY KEY (feed_key, week_start)
);
CREATE TABLE IF NOT EXISTS multibot.forex_calendar_attempts (
    feed_key TEXT NOT NULL, week_start TEXT NOT NULL, attempted_at TEXT NOT NULL,
    error TEXT NOT NULL, PRIMARY KEY (feed_key, week_start)
);
CREATE TABLE IF NOT EXISTS multibot.multibot_migrations (
    migration_key TEXT PRIMARY KEY, completed_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS multibot.app_config (
    config_key TEXT PRIMARY KEY, payload TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS multibot.runtime_leases (
    lease_key TEXT PRIMARY KEY, owner_id TEXT NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL, updated_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS signal_events_timestamp_idx ON multibot.signal_events(timestamp DESC);
CREATE INDEX IF NOT EXISTS deliveries_signal_idx ON multibot.deliveries(signal_id, attempted_at DESC);
CREATE INDEX IF NOT EXISTS deliveries_signal_id_idx ON multibot.deliveries(signal_id, id DESC);
CREATE INDEX IF NOT EXISTS scan_runs_started_idx ON multibot.scan_runs(started_at DESC);

REVOKE ALL ON ALL TABLES IN SCHEMA multibot FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA multibot
    REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;
